"""Imitation-learning comparison -- see original docstring for full
rationale (train_imitation_tictactoe.py, first version). This version:
fixes import paths after the agents/ restructure, points MODELS_DIR at
models/tictactoe/, and replaces the hardcoded SHUFFLE_STATES/
SLEEP_EVERY_N_STATES/USE_SYMMETRY module constants with CLI flags so all
5 known variants can be regenerated by invocation instead of manual edits.

--agent v2 uses the cache-backed ConnectomeTicTacToeAgentV2 (gate="none"):
same train() calls, same weights trajectory as v1 (verified equal in
scripts/tictactoe/verify_v2_matches_v1.py) -- just skips train()'s
trailing readout pass and speeds up the full-coverage eval loop
afterward, which calls value() once per legal action per state.
Run verify_v2_matches_v1.py first if you haven't already before trusting
--agent v2 output.
"""
import argparse
import os
import random
import sys
import time

_THIS_DIR = os.path.dirname(os.path.abspath(__file__))            # scripts/tictactoe
_SCRIPTS_DIR = os.path.dirname(_THIS_DIR)                          # scripts
_ROOT = os.path.dirname(_SCRIPTS_DIR)                              # my_experiments
for _p in (_THIS_DIR, _ROOT, os.path.join(_SCRIPTS_DIR, "diagnostics")):
    if _p not in sys.path:
        sys.path.insert(0, _p)

from tictactoe_solver import enumerate_reachable_states, minimax
from tictactoe_coverage_eval import to_perspective, afterstate, full_coverage_accuracy
from agents.tictactoe.connectome_tictactoe_agent import ConnectomeTicTacToeAgent
from agents.tictactoe.connectome_tictactoe_agent_v2 import ConnectomeTicTacToeAgentV2
from agents.shared.symmetry_wrapper import SymmetryWrapper
from run_tictactoe import sample_early_boards

REPS_PER_STATE = 3
ESTIMATE_AFTER = 200
MODELS_DIR = os.path.join(_ROOT, "models", "tictactoe")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--shuffle", dest="shuffle", action="store_true", default=True)
    ap.add_argument("--no-shuffle", dest="shuffle", action="store_false")
    ap.add_argument("--sleep-every", type=int, default=None)
    ap.add_argument("--symmetry", dest="symmetry", action="store_true", default=True)
    ap.add_argument("--no-symmetry", dest="symmetry", action="store_false")
    ap.add_argument("--agent", choices=["v1", "v2"], default="v1")
    args = ap.parse_args()

    states = enumerate_reachable_states()
    if args.shuffle:
        random.Random(0).shuffle(states)
    print(f"{len(states)} reachable non-terminal states to imitation-train on "
          f"({REPS_PER_STATE} reps each, 2 train() calls per rep = "
          f"~{len(states) * REPS_PER_STATE * 2} train() calls total)")
    print(f"toggles: shuffle={args.shuffle}  sleep_every={args.sleep_every}  "
          f"symmetry={args.symmetry}  agent={args.agent}")

    calibration_boards = sample_early_boards(300)
    AgentCls = ConnectomeTicTacToeAgent if args.agent == "v1" else ConnectomeTicTacToeAgentV2
    base_agent = AgentCls()
    agent = SymmetryWrapper(base_agent) if args.symmetry else base_agent
    agent.calibrate_baseline(calibration_boards)

    t0 = time.time()
    for i, (raw_board, mover) in enumerate(states):
        _, best_a = minimax(raw_board, mover)
        board_mine = to_perspective(raw_board, mover)
        legal = [a for a in range(9) if board_mine[a] == 0]
        others = [a for a in legal if a != best_a]
        if others:
            other_a = random.choice(others)
            best_after = afterstate(board_mine, best_a)
            other_after = afterstate(board_mine, other_a)
            for _ in range(REPS_PER_STATE):
                agent.update_episode([best_after], 1)
                agent.update_episode([other_after], -1)

        if args.sleep_every and (i + 1) % args.sleep_every == 0:
            base_agent.sleep()

        if i == ESTIMATE_AFTER:
            elapsed = time.time() - t0
            per_state = elapsed / ESTIMATE_AFTER
            print(f"~{per_state:.3f}s/state -> estimated total "
                  f"{per_state * len(states) / 60:.1f} min for all {len(states)} states.")
        if i % 500 == 0 and i > 0:
            print(f"{i}/{len(states)} states done ({time.time() - t0:.0f}s elapsed)")

    print(f"training done in {time.time() - t0:.0f}s. evaluating full-coverage accuracy...")
    acc, correct, total = full_coverage_accuracy(agent, states)
    print(f"\nfull-coverage accuracy: {correct}/{total} = {acc:.1f}%  "
          f"(previous shuffle+symmetry result: 61.8%, previous baseline: 53.8%, untrained: 54.7%)")

    os.makedirs(MODELS_DIR, exist_ok=True)
    suffix = "".join([
        "_shuffle" if args.shuffle else "",
        f"_sleep{args.sleep_every}" if args.sleep_every else "",
        "_symmetry" if args.symmetry else "",
    ])
    save_path = os.path.join(MODELS_DIR, f"connectome_imitation{suffix}")
    base_agent.save(save_path)
    print(f"saved to {save_path}_weights.npz / {save_path}_baseline.npy")


if __name__ == "__main__":
    main()
